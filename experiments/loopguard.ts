import * as crypto from 'crypto';

class LoopGuard {
    private history: string[] = [];
    private readonly maxHistory: number;

    constructor(maxHistory: number = 3) {
        this.maxHistory = maxHistory;
    }

    /**
     * Calculates the SHA-256 hash of a file's contents.
     * Returns true if the formation is fresh and safe to run,
     * or false if we're running in circles (infinite loop detected!).
     */
    public registerState(fileContent: string): boolean {
        // Calculate the cryptographic fingerprint of the play
        const stateHash = crypto
            .createHash('sha256')
            .update(fileContent, 'utf8')
            .digest('hex');

        // Check if we've already run this exact play
        if (this.history.includes(stateHash)) {
            return false; // 🛑 Flag on the play! Infinite loop detected.
        }

        // Add the new play to our scouting clipboard
        this.history.push(stateHash);

        // Keep our clipboard light (only track the most recent plays)
        if (this.history.length > this.maxHistory) {
            this.history.shift(); // Remove the oldest play on the list
        }

        return true; // ✅ Clear for kickoff! Safe to run.
    }
}

// --- 🎮 Play-by-Play Simulation ---

const guard = new LoopGuard();

// Simulated code formations generated by our agent across 3 quarters
const codeIterations: string[] = [
    "function run() { return 1; }", // Quarter 1: Clean pass
    "function run() { return 2; }", // Quarter 2: Sweeper play
    "function run() { return 1; }",  // Quarter 3: Uh oh! Re-running Quarter 1's play.
    "function run() { return 2; }", // Quarter 2: Sweeper play
];

codeIterations.forEach((code, index) => {
    const isSafe = guard.registerState(code);
    console.log(`[Quarter ${index + 1}] Play Checked. Clear to snap the ball? ${isSafe ? '✅ YES' : '❌ NO - PENALTY!'}`);
});
